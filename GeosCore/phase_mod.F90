! !IROUTINE: GET_Tg_BOCPO
!
! !DESCRIPTION: Function GET_Tg_BOCPO caculate and returns Tg for primary
! biomass burning hydrophobic OA
!\\
!\\
! !INTERFACE:
!
  SUBROUTINE GET_Tg_BOCPO( Input_Opt,  State_Chm, State_Diag,                &
                           State_Grid, State_Met, RC                        )


!
! !USES:
!
   USE ERROR_MOD 
   USE ErrCode_Mod
   USE Input_Opt_Mod,      ONLY : OptInput
   USE State_Chm_Mod,      ONLY : ChmState
   USE State_Met_Mod,      ONLY : MetState
   USE State_Diag_Mod,     ONLY : DgnState
   USE State_Grid_Mod,     ONLY : GrdState

!
! !INPUT PARAMETERS:
!
   TYPE(OptInput), INTENT(IN) :: Input_Opt       ! Input Options object
   TYPE(ChmState), INTENT(IN) :: State_Chm       ! Chemistry State object
   TYPE(MetState), INTENT(IN) :: State_Met       ! Meteorology State object
   TYPE(GrdState), INTENT(IN) :: State_Grid      ! Grid State object

!
!
! !INPUT/OUTPUT PARAMETERS:
!
   TYPE(DgnState), INTENT(INOUT) :: State_Diag   ! Diagnostics State object
!
! !OUTPUT PARAMETERS:
!
   INTEGER,        INTENT(OUT)   :: RC           ! Success or failure?

!
! Yumin Li 16/05/2024
!EOP
!------------------------------------------------------------------------------
!BOC
!
! !LOCAL VARIABLES:
!
   ! SAVED scalars
   LOGICAL, SAVE      :: FIRST = .TRUE.
    
   ! Scalars
   INTEGER             :: I,           J,           L
   
   REAL(fp):: Kphase                 ! mass based hygroscopicity parameter
   REAL(fp):: TgDry                  ! Tg for BB OCPO at dry consition 
   REAL(fp):: Tg_K                   ! Real time Tg in [K]
   REAL(fp):: T0Dry                  ! T0 dry [K]
   REAL(fp):: T0                     ! T0 consider the RH [K]
   REAL(fp):: MW_BB = 248e+0_fp      ! molecular weight for BB OA [g mol-1]
   REAL(fp):: MW_Water = 18.02e+0_fp ! molecular weight for water [g mol-1]
   REAL(fp):: Df = 10e+0_fp          ! fragility parameter assumed as 10 [unitless]
   REAL(fp):: w1                     ! fraction of OA, 1-w1 is the fraction of water
   REAL(fp):: w0                     ! fraction for caculate w1
   REAL(fp):: RH                     ! RH
   REAL(fp):: aw                     ! RH/100
   REAL(fp):: Troom = 293e+0_fp      ! room temperature
   REAL(fp):: logV, logVD            ! log viscosity, log viscosity dry at 293 K
   REAL(fp):: logVW = -3e+0_fp       ! log viscosity for water
   REAL(fp):: logV_K                 ! Real time log viscosity 
   REAL(fp):: T                      ! Temperature [K]

    ! Strings
    CHARACTER(LEN=255)  :: errMsg,      thisLoc
    ! pointers
    REAL(fp),      POINTER  :: Tg(:,:,:,:)
    REAL(fp),      POINTER  :: Viscosity(:,:,:,:)
 
    ! Initialize pointers
    Tg                   => State_Chm%Tg
    Viscosity            => State_Chm%Viscosity


   !=================================================================
   ! GET_Tg begins here!
   !=================================================================
   
   ! Initialize
   RC      = GC_SUCCESS
   errMsg  = ''
   thisLoc = ' -> at GET_Tg_BOCPO (in module GeosCore/phase_mod.F90)'

   IF ( .not. Input_Opt%ITS_A_FULLCHEM_SIM ) RETURN

   ! get number for Kphase and TgDry
   Kphase = Kphase_BOCPO
   TgDry  = TgDry_BOCPO

   !========================================================================
   ! First-time setup
   !========================================================================
   IF ( FIRST ) THEN

   ! get number for Kphase and TgDry
   Kphase = Kphase_BOCPO
   TgDry  = TgDry_BOCPO

      ! Reset first-time flag
      FIRST  = .FALSE.
   ENDIF
   

    !========================================================================
    ! Loop over surface boxes and compute Tg
    !========================================================================
    !$OMP PARALLEL DO       &
    !$OMP DEFAULT( SHARED ) &
    !$OMP PRIVATE( I, J, L )&
    !$OMP PRIVATE( Tg_K, logV_K, T0Dry, logVD, logV, T0)&
    !$OMP PRIVATE( T, RH, aw, w0, w1)

    DO L = 1, State_Grid%NZ
    DO J = 1, State_Grid%NY
    DO I = 1, State_Grid%NX


    ! Zero numbers
    Tg(I,J,L,1) = 0.0e+0_fp
    Viscosity(I,J,L,1) = 0.0e+0_fp
    TgBOCPO(I,J,L)  = 0.0e+0_fp
    
    ! Calculation start here

    T0Dry = 39.17e+0_fp * TgDry / (Df + 39.17e+0_fp)

    RH    = State_Met%RH(I, J, L)
    ! Manually set the value of aw not to exceed 0.99
    aw    = MIN( 0.99_fp, State_Met%RH(I,J,L) * 1.0e-2_fp )
    T     = State_Met%T(I,J,L)

    w0 = 1e+0_fp
    w1 = 1e+0_fp
 
    IF (RH > 0) THEN


    w0 = 1e+0_fp / (1e+0_fp + Kphase * aw/(1e+0_fp-aw) )
    w1 = (w0 / MW_BB)/(w0 / MW_BB + (1e+0_fp-w0)/MW_Water)

    IF (w1>1.or.w1<0.and. L ==2) print*, 'w1 not in (0-1):', w1, 'aw:', aw , 'RH', RH

       ! Prevent underflow condition
       IF ( w1 < 1e-20_fp )   THEN
   
       w1    = 0.0e+0_fp

       ELSEIF ( w1 > 1    )   THEN
       w1    = 1.0e+0_fp

       ENDIF


    logVD = -5e+0_fp + 0.434e+0_fp * Df * T0Dry/ (Troom-T0Dry)

   ! realtime logV
    logV  = w1 * logVD + (1e+0_fp-w1) * logVW 

    T0    = Troom * (5e+0_fp + logV) / (5e+0_fp + logV + 0.434e+0_fp * Df)   
    Tg_K  = T0 * (Df + 39.17e+0_fp)/ 39.17e+0_fp
   
    ELSE

    Tg_K = TgDry
    T0 = 39.17e+0_fp * Tg_K / (Df + 39.17e+0_fp)

    ENDIF
 
    logV_K = -5e+0_fp + 0.434e+0_fp * Df*T0/(T-T0)


    Tg(I,J,L,1)        = Tg_K
    Viscosity(I,J,L,1) = logV_K
    TgBOCPO(I,J,L)     = Tg_K

    !---------------------------------------------------------------------
    ! HISTORY 
    !---------------------------------------------------------------------
    IF ( State_Diag%Archive_Phase ) THEN
 
    IF (State_Diag%Archive_TgBOCPO) THEN
        State_Diag%TgBOCPO(I,J,L) = Tg_K
    ENDIF

    IF (State_Diag%Archive_ViscosityBOCPO) THEN
        State_Diag%ViscosityBOCPO(I,J,L) = logV_K
    ENDIF
 
    ENDIF


!--------------------------for test -------------------
!    IF (I ==58 .AND. J ==31 .AND. L ==1) print*, 'Tg_BOCPO:', Tg_K, Tg(I,J,L,1), TgBOCPO(I,J,L), 'RH:', RH, 'w1:', w1
!    IF (I ==58 .AND. J ==31 .AND. L ==1) print*, 'logV_BOCPO:', logV_K, Viscosity(I,J,L,1), 'T:', T
!-----------------------------------------------------
    ENDDO
    ENDDO
    ENDDO
    !$OMP END PARALLEL DO

    ! Free pointers:
    Tg       => NULL()
    Viscosity=> NULL()

 END SUBROUTINE GET_Tg_BOCPO
