    !$OMP PRIVATE( T, RH )


    DO L = 1, State_Grid%NZ
    DO J = 1, State_Grid%NY
    DO I = 1, State_Grid%NX

    RH    = State_Met%RH(I, J, L)
    T     = State_Met%T(I,J,L)
    T0    = 0.0_fp
    Tg_K  = 0.0_fp

    IF ( Input_Opt%LSVPOA ) THEN  !yuminli add for semi POA
    ! Get the different source OA concentration in mol/mol dry air
    POA1  = Spc(id_POA1)%Conc(I,J,L)
    POA2  = Spc(id_POA2)%Conc(I,J,L)
    OPOA1  = Spc(id_OPOA1)%Conc(I,J,L)
    OPOA2  = Spc(id_OPOA2)%Conc(I,J,L)

    ELSE
    ! Get the different source OA concentration in mol/ mol dry air 
    OCPO  = Spc(id_OCPO)%Conc(I,J,L)

    OCPI  = Spc(id_OCPI)%Conc(I,J,L)
    ENDIF

    ! Get the SOA species, here only for complex SOA

    B_SOA =  Spc(id_TSOA0)%Conc(I,J,L) + Spc(id_TSOA1)%Conc(I,J,L)   &
            + Spc(id_TSOA2)%Conc(I,J,L) + Spc(id_TSOA3)%Conc(I,J,L)  &
            + Spc(id_SOAGX)%Conc(I,J,L) + Spc(id_SOAIE)%Conc(I,J,L)  &
            + Spc(id_LVOCOA)%Conc(I,J,L)                             &
             + Spc(id_IONITA)%Conc(I,J,L) + Spc(id_MONITA)%Conc(I,J,L)  

    A_SOA = Spc(id_ASOAN)%Conc(I,J,L) + Spc(id_ASOA1)%Conc(I,J,L)    &
            + Spc(id_ASOA2)%Conc(I,J,L) + Spc(id_ASOA3)%Conc(I,J,L)  &
            + Spc(id_AONITA)%Conc(I,J,L)


    ! mass & weight average
    ! OCPO: 1.4 * 12 g/mol
    ! OCPI: 2.1 * 12 g/mol
    ! SOA : 250 g/mol

    IF ( Input_Opt%LSVPOA ) THEN

        TOA =   (A_SOA + B_SOA) * MF_SOA &
              + (POA1 + POA2)   * MF_EPOA &
              + (OPOA1 + OPOA2) * MF_OPOA
       
      IF (TOA > 0.0_fp) THEN
         Tg_K = (POA1 + POA2 ) *MF_EPOA /TOA * Tg(I,J,L,1) &    ! POA  ==> OCPO
              + (OPOA1 +OPOA2) *MF_OPOA /TOA * Tg(I,J,L,2) &    ! OPOA ==> OCPI
              +  B_SOA         *MF_SOA  /TOA * Tg(I,J,L,5) &
              +  A_SOA         *MF_SOA  /TOA * Tg(I,J,L,6)
      ELSE
        Tg_K = ( Tg(I,J,L,1)+Tg(I,J,L,2)+Tg(I,J,L,5)+Tg(I,J,L,6))/ 4.0_fp

      ENDIF

    ELSE

      TOA    = OCPO * MF_EPOA + OCPI * MF_OPOA + (A_SOA + B_SOA) * MF_SOA
 
      IF (TOA > 0.0_fp) THEN    

         Tg_K = OCPO*MF_EPOA /TOA * Tg(I,J,L,1) &
              + OCPI*MF_OPOA /TOA * Tg(I,J,L,2) &
              + B_SOA*MF_SOA /TOA * Tg(I,J,L,5) &
              + A_SOA*MF_SOA /TOA * Tg(I,J,L,6)
      ELSE 
        Tg_K = ( Tg(I,J,L,1)+Tg(I,J,L,2)+Tg(I,J,L,5)+Tg(I,J,L,6))/ 4.0_fp
      ENDIF

    ENDIF

    IF (Tg_K >= T) THEN
!!! Use Df = 30 for pure OA

      T0 = 39.17e+0_fp * Tg_K / (30.0e+0_fp + 39.17e+0_fp)
      logV_K = -5e+0_fp + 0.434e+0_fp * 30.0e+0_fp*T0/(T-T0)

      IF (I ==58 .AND. J ==31 .AND. L ==1) print*, 'T0:', T0, 'Df = 30', Df

    ELSE

     T0 = 39.17e+0_fp * Tg_K / (Df + 39.17e+0_fp)
     logV_K = -5e+0_fp + 0.434e+0_fp * Df*T0/(T-T0)


     IF (I ==58 .AND. J ==31 .AND. L ==1) print*, 'T0:', T0, 'Df = 10', Df, 'logV_K:', logV_K

    ENDIF

    Tg(I,J,L,7) = Tg_K
    Viscosity(I,J,L,7) = logV_K
    TgMEAN(I,J,L) = Tg_K

    !---------------------------------------------------------------------
    ! HISTORY
    !---------------------------------------------------------------------
    IF ( State_Diag%Archive_Phase ) THEN

    IF (State_Diag%Archive_TgMEAN) THEN
        State_Diag%TgMEAN(I,J,L) = Tg_K
    ENDIF
    IF (State_Diag%Archive_ViscosityMEAN) THEN
        State_Diag%ViscosityMEAN(I,J,L) = logV_K
    ENDIF

    ENDIF

!----------------------------------------for test---------------------------
!    IF (I ==58 .AND. J ==31 .AND. L ==1) print*, 'w1:', w1
!    IF (I ==58 .AND. J ==31 .AND. L ==1) print*, 'Tg_MEAN:', Tg_K, Tg(I,J,L,7),TgMEAN(I,J,L), 'RH:', RH
!    IF (I ==58 .AND. J ==31 .AND. L ==1) print*, 'logV_MEAN:', logV_K, Viscosity(I,J,L,7), 'T:', T, 'T0:', T0
!---------------------------------------------------------------------------

    ENDDO
    ENDDO
    ENDDO
    !$OMP END PARALLEL DO

    ! Free pointers
    Tg      => NULL()

 END SUBROUTINE GET_Tg_MEAN
